/** Texto de una clave en el idioma del portal; `{x}` se reemplaza por `vars.x`. */
export function tx(key, vars) {
  const e = TXT[key];
  let s = e ? e[window.GameIt?.prefs?.lang === 'en' ? 'en' : 'es'] || e.es : key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}
export const lang = () => (window.GameIt?.prefs?.lang === 'en' ? 'en' : 'es');
export const pick = (o) => (o ? o[lang()] || o.es : '');
