/** `t(clave, { n: 3 })`: el texto en el idioma elegido en el portal. */
export function makeT(G) {
  return (key, vars) => {
    const e = TXT[key];
    let s = e ? G.t(e) : key;
    if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
    return s;
  };
}
